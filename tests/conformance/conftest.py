@pytest.fixture
def landing(tmp_path: Path) -> Landing:
    """An empty landing tree, shared by both front doors of a scenario.

    Shared rather than duplicated on purpose: if the two doors read different
    trees, a parity failure could be a fixture difference rather than a
    duckstream difference, and the whole check would be weaker for it.
    """
    return Landing(tmp_path / "landing")


@pytest.fixture
def make_parity(tmp_path: Path, landing: Landing) -> Callable[..., Parity]:
    """Build a :class:`~harness.Parity` for a scenario, over the shared tree."""

    made: list[Parity] = []

    def factory(scenario: Scenario = ADDITIVE, *, name: str | None = None) -> Parity:
        label = name or f"case{len(made)}"
        parity = Parity(tmp_path / label, landing, scenario)
        made.append(parity)
        return parity

    return factory


@pytest.fixture
def parity(make_parity: Callable[..., Parity]) -> Parity:
    """The phase-1 additive scenario, behind both front doors."""
    return make_parity()


@pytest.fixture
def make_world(tmp_path: Path, landing: Landing) -> Callable[..., World]:
    """A single-door world, for tests where the two doors cannot move together.

    Fault injection is the main case: a killed process leaves one catalog
    mid-flight, and asserting about it needs that catalog on its own. Those
    tests parametrise over :data:`harness.DOORS` instead, so both doors are
    still covered -- just not in lockstep.

    Using this fixture without either parametrising over ``DOORS`` or appearing
    in :data:`SINGLE_DOOR_EXEMPTIONS` is a test failure; see
    :func:`_door_choice_guard`.
    """

    made: list[World] = []

    def factory(door: str, scenario: Scenario = ADDITIVE) -> World:
        world = World(door, tmp_path / f"{door}{len(made)}", landing, scenario)
        made.append(world)
        return world

    return factory
